/** 常用图标名称列表 */
const ICON_LIST = Object.keys(iconComponentMap)

/** 根据名称获取图标组件（用于 <component :is>） */
export function getIconComponent(name: string): Component | undefined {
  return iconComponentMap[name]
}

export function useIconSelector() {
  const iconSearchText = ref('')
  const selectedIcon = ref('')

  const filteredIcons = computed(() => {
    const q = iconSearchText.value.toLowerCase().trim()
    if (!q) return ICON_LIST
    return ICON_LIST.filter((name) => name.toLowerCase().includes(q))
  })

  function openIconPicker(currentIcon?: string): void {
    selectedIcon.value = currentIcon || ''
    iconSearchText.value = ''
  }

  function selectIcon(name: string): void {
    selectedIcon.value = name
  }

  function clearIcon(): void {
    selectedIcon.value = ''
  }

  return {
    ICON_LIST,
    iconSearchText,
    selectedIcon,
    filteredIcons,
    openIconPicker,
    selectIcon,
    clearIcon
  }
}
